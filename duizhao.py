def text_ratio(a, b):
    """兩段引文的相似度。標點不計，異體字靠比例容忍，不另立字表。"""
    strip = str.maketrans("", "", "，。；：、！？「」『』（）()")
    return difflib.SequenceMatcher(
        None, (a or "").translate(strip), (b or "").translate(strip)).ratio()


