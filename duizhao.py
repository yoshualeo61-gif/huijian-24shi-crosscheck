def span_overlap(a, b):
    """兩書的紀事年代是否重疊 —— 不重疊就沒有可比之事。

    《三國志》（184–280）與《明史》（1368–1644）之間無論怎麼湊
    人名地名都不是同一件事。無斷代資料時不排除，寧可多報不可漏報。
    """
    sa, sb = BOOK_SPAN.get(a or ""), BOOK_SPAN.get(b or "")
    if not sa or not sb:
        return True
    return sa[0] <= sb[1] and sb[0] <= sa[1]

