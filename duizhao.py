# 兩個紀年都已知、且相差超過這個年數，就判為兩件事，不再並置。
YEAR_GAP_MAX = 2


def pair_score(a, b):
    """三重錨定。人物最重，紀年次之，地點再次。

    已知而相衝的紀年是**否證**，不只是「不加分」。實測教訓：
    徐玄明殺張稷（513）曾與郁洲獻白鹿（475）配成一組 —— 相隔三十八年,
    只因同地點（＋2）又同月（＋2）剛好達到門檻 4，接著 diverge 還把
    那三十八年的落差報成一條權重 5 的「紀年歧異」，湊成權重 9。
    """
    s, why = 0, []
    if (a["year"] and b["year"]
            and abs(a["year"][0] - b["year"][0]) > YEAR_GAP_MAX):
        return 0, []                     # 年代相去太遠，不是同一事
    # 一個月裡每個日干支最多出現一次，所以同月而干支不同就是兩天。
    # 行為又無重疊時判為兩件事 —— 實測《梁書》「十二月丙申，以國子祭酒
    # 張稷為護軍將軍」曾與《南史》「十二月丙寅，…率兵入殿殺帝」配成
    # 一組，只靠同人物（＋3）同月（＋2）就過了門檻。
    # 行為重疊時不否證：那才是兩書對同一事各繫一日，即日次歧異。
    if (a["month"] and a["month"] == b["month"] and a["leap"] == b["leap"]
            and a["ganzhi"] and b["ganzhi"] and a["ganzhi"] != b["ganzhi"]
            and not (a["acts"] & b["acts"])):
        return 0, []
    if a["person"] and a["person"] == b["person"]:
        s += 3
        why.append(f"同人物 {a['person']}")
    if a["place"] and a["place"] == b["place"]:
        s += 2
        why.append(f"同地點 {a['place']}")
    if a["year"] and b["year"]:
        d = abs(a["year"][0] - b["year"][0])
        if d == 0:
            s += 3
            why.append(f"同年 {a['year'][0]}")
        elif d == 1:
            s += 1
            why.append(f"相鄰年 {a['year'][0]}/{b['year'][0]}")
    if a["month"] and a["month"] == b["month"] and a["leap"] == b["leap"]:
        s += 2
        why.append(f"同月 {'閏' if a['leap'] else ''}{a['month']}月")
    # 干支日只在同月的前提下才算錨：日干支六十日一輪，離開月份毫無分辨力
    if (a["ganzhi"] and a["ganzhi"] == b["ganzhi"]
            and a["month"] and a["month"] == b["month"]):
        s += 3
        why.append(f"同日 {a['ganzhi']}")
    if a["acts"] & b["acts"]:
        s += 1
        why.append("行為重疊 " + "、".join(sorted(a["acts"] & b["acts"])))
    return s, why


def diverge(ra, rb, aa, ab):
    """並置之後，分歧在哪。"""
    out = []
    # 一方的紀年寫法是另一方的後綴（「二年二月」vs「延昌二年二月」）時,
    # 那是檢索窗口截掉了年號，不是歧異。
    ta_, tb_ = (ra.get("time") or ""), (rb.get("time") or "")
    compatible = bool(ta_) and bool(tb_) and (ta_ in tb_ or tb_ in ta_)
    if (aa["year"] and ab["year"] and aa["year"][0] != ab["year"][0]
            and not compatible):
        why = (f"{ra['book']}作{aa['year'][1]}{aa['year'][2]}年"
               f"（{aa['year'][0]}）／{rb['book']}作{ab['year'][1]}{ab['year'][2]}年"
               f"（{ab['year'][0]}）")
        wt = 5
        # 差一年又涉及改元之年：很可能只是改元月份的算法差異，不是歧異。
        # 本工具不處理月份邊界（見文檔 06），所以這裡降權並說明。
        if (abs(aa["year"][0] - ab["year"][0]) == 1
                and (aa["first_year"] or ab["first_year"])):
            wt = 2
            why += ("　差一年且一方為改元元年：改元當年前幾個月仍屬舊年號，"
                    "本工具不處理月份邊界，此條很可能不是真歧異，權重已下調。")
        out.append((wt, "紀年歧異", why))

    # 同年同月而干支日不同：日次歧異，考異的細處入口
    if (aa["ganzhi"] and ab["ganzhi"] and aa["ganzhi"] != ab["ganzhi"]
            and aa["month"] and aa["month"] == ab["month"]
            and aa["year"] and ab["year"] and aa["year"][0] == ab["year"][0]):
        out.append((3, "日次歧異",
                    f"同年同月，{ra['book']}作{aa['ganzhi']}日／"
                    f"{rb['book']}作{ab['ganzhi']}日。"))
    # 閏月之別
    if (aa["month"] and aa["month"] == ab["month"] and aa["leap"] != ab["leap"]):
        out.append((3, "閏月歧異",
                    f"{ra['book']}作{'閏' if aa['leap'] else ''}{aa['month']}月／"
                    f"{rb['book']}作{'閏' if ab['leap'] else ''}{ab['month']}月。"))

    ta, tb = lex_tags(ra["evidence"]), lex_tags(rb["evidence"])
    for x, y in OPPOSED:
        if (x in ta and y in tb) or (y in ta and x in tb):
            out.append((5, "立場用語對立",
                        f"同一事，{ra['book']}記作「{x if x in ta else y}」、"
                        f"{rb['book']}記作「{y if x in ta else x}」。春秋筆法之直接證據。"))
    if "蔑稱" in ta or "蔑稱" in tb:
        out.append((2, "蔑稱", "一方使用貶稱，敘述已帶判斷。"))

    ea, eb = aa["acts"], ab["acts"]
    if ea and eb and not (ea & eb):
        out.append((3, "行為不重疊",
                    f"{ra['book']}記「{'、'.join(sorted(ea))}」／"
                    f"{rb['book']}記「{'、'.join(sorted(eb))}」。同一事而所記不同。"))
    return out


def align(rows, threshold=4, cross_stance_only=True):
    """並置值得並置的兩條。

    `cross_stance_only` 是兩個條件之一即可（v0.2.6 起）：

    1. **源流關係** —— 同陣營也要比。《梁書》對其唐修派生本《南史》
       正是最有價值的一組（「斬東昏」／「殺帝」），把它當同陣營濾掉
       就全丟了。源流對只算其出入，見下。
    2. **不同陣營且斷代重疊** —— 陣營用 `CAMP`（替誰說話），不是
       `COMPILER`（誰修的）。舊版混用一條，於是《宋史》《遼史》
       《金史》同為「元修」而永不比對。
    """
    A = [anchors(r) for r in rows]
    pairs = []
    for i, j in itertools.combinations(range(len(rows)), 2):
        ba, bb = rows[i].get("book", ""), rows[j].get("book", "")
        rel = derivation(ba, bb)
        if cross_stance_only and not rel:
            if A[i]["stance"] == A[j]["stance"]:
                continue
            if not span_overlap(ba, bb):
                continue
        s, why = pair_score(A[i], A[j])
        if s < threshold:
            continue
        d = diverge(rows[i], rows[j], A[i], A[j])
        if rel:
            # 源流對：派生本與史源逐字雷同是常態，所以**錨定一致不計分**,
            # 那只是抄錄。有意義的只有出入 —— 那是看得見的改筆。
            # 全無出入的源流對直接不報：實測權重最高的一組是《梁書》
            # 「为」對《南史》「爲」，差別只有一個異體字。
            if not d:
                # 一條已分類的出入都沒有，先看兩段文字是不是幾乎一樣。
                # 幾乎一樣 → 純抄錄，沒有信息（《梁書》「为」對《南史》
                # 「爲」）。差得明顯卻一條都歸不了類 → 有出入而本工具的
                # 詞表叫不出名字，那要報出來，不能靜默丟掉 ——
                # 初版的這個 continue 把《梁書》「斬東昏」對《南史》
                # 「殺帝」整組丟了，而那正是本案例最有價值的一條。
                if text_ratio(rows[i].get("evidence"),
                              rows[j].get("evidence")) >= COPY_RATIO:
                    continue
                d = [(1, "出入未能歸類",
                      "兩處敘述明顯不同，但本工具的立場詞表歸不出類別，"
                      "須人工比讀。詞表不完備是已知局限，不是此處無異。")]
            d = [(w, "改筆" if k == "立場用語對立" else k, t) for w, k, t in d]
            pairs.append({"a": rows[i], "b": rows[j], "score": s,
                          "anchors": why, "diverge": d,
                          "relation": ("源流", rel[0], rel[1]),
                          "weight": sum(w for w, _, _ in d)})
        else:
            # 不同陣營卻同一批人修的（元修三史即是），其互相一致不如
            # 各自獨立成書者有力 —— 兩書可能共用同一份底本或同一道
            # 刪裁。這不是否證，是給權重打個折扣的提醒。
            if ba and ba == bb:
                # 同一部書之內的兩個陣營（《三國志》的魏志對蜀志、
                # 《舊五代史》的後梁對後唐）。措辭之異出自同一位史家
                # 的取捨，不是兩個傳統各說各話 —— 作為春秋筆法的證據,
                # 這比跨書的異文更直接，因為兩段都是他寫的。
                # 錨定仍計分：陳壽各志所據的檔案本不相同，相合有意義。
                d = list(d) + [
                    (0, "同書異志：一人之筆",
                     f"兩條同出《{ba}》，分屬{A[i]['stance']}與"
                     f"{A[j]['stance']}。所異出於一人取捨，非兩傳統各執"
                     f"一詞；所同則因各志所據檔案本不相同，仍有互證之力。")]
            elif COMPILER.get(ba) and COMPILER.get(ba) == COMPILER.get(bb):
                d = list(d) + [
                    (0, "同修：互證力較弱",
                     f"《{ba}》《{bb}》同為{COMPILER[ba]}，雖分屬"
                     f"{A[i]['stance']}與{A[j]['stance']}，仍出自同一次"
                     f"修史工程，其一致不如各自獨立成書者有力。")]
            pairs.append({"a": rows[i], "b": rows[j], "score": s,
                          "anchors": why, "diverge": d,
                          "relation": ("獨立", None, None),
                          "weight": s + sum(w for w, _, _ in d)})
    return sorted(pairs, key=lambda p: -p["weight"])


def show(pairs, fh=sys.stdout):
    print(f"\n{'='*70}\n事件對照 {len(pairs)} 組\n{'='*70}", file=fh)
    for p in pairs:
        a, b = p["a"], p["b"]
        rel = p.get("relation") or ("獨立", None, None)
        if rel[0] == "源流":
            print(f"\n■ 權重 {p['weight']}　【源流對】《{rel[1]}》刪削自"
                  f"《{rel[2]}》—— 雷同是抄錄，不計互證分，以下只列其出入",
                  file=fh)
            print(f"　　（同事錨定：{'；'.join(p['anchors'])}）", file=fh)
        else:
            print(f"\n■ 權重 {p['weight']}　錨定：{'；'.join(p['anchors'])}",
                  file=fh)
        for w, k, why in p["diverge"]:
            print(f"  {'⚠' if w >= 4 else '·'} {k}　{why}", file=fh)
        for r in (a, b):
            print(f"\n    〔{r['stance']}〕《{r['book']}·{r['juan']}》"
                  f" {r.get('time') or '—'}", file=fh)
            print(f"      「{r['evidence']}」", file=fh)
        print("  " + "─" * 66, file=fh)




# ── 年號表的自我核對 ──────────────────────────────────────
NUM_RE = "[元一二三四五六七八九十]+"

# 各朝起訖，用來核對年號表第三欄（朝代）與第二欄（元年）對不對得上。
# 不拿「提到這個年號的書」來核：追述前朝年號是常態 ——《宋史》提
# 「開元」九次，那不是錯，是宋人引唐事。初版拿它作判準，26 條全是假警報。
DYNASTY_SPAN = {
    "西漢": (-206, 8), "東漢": (25, 220), "曹魏": (220, 265),
    "西晉": (265, 317), "東晉": (317, 420),
    "蜀漢": (221, 263), "孫吳": (222, 280),
    "南": (420, 589), "北": (386, 581), "陳": (557, 589),
    "隋": (581, 618), "唐": (618, 907),
    "後梁": (907, 923), "後唐": (923, 936), "後晉": (936, 947),
    "後漢": (947, 951), "後周": (951, 960),
    "遼": (907, 1125), "宋": (960, 1279), "金": (1115, 1234),
    "元": (1206, 1368), "明": (1368, 1644),
}


def _corpus_text(root="corpus"):
    """各書全文。核對年號表要用整個語料，不只檢索命中的那幾卷。"""
    out = {}
    for d in sorted(pathlib.Path(root).iterdir()):
        if d.is_dir():
            out[d.name] = "\n".join(
                f.read_text(encoding="utf-8", errors="ignore")
                for f in d.glob("*.txt"))
    return out


_LONGER = {}


def _longer_eras(era):
    """以這個年號為後綴的更長年號。「大通」→（「中大通」,）。"""
    if era not in _LONGER:
        _LONGER[era] = tuple(e for e, _, _ in ERAS
                             if len(e) > len(era) and e.endswith(era))
    return _LONGER[era]


def era_usage(text, era):
    """這個年號在語料裡用到第幾年，以及出現在哪幾部書。

    只採出現 ≥2 次的最大年次：孤例往往是錯字、他國紀年，或根本不是
    年號（《宋史》律曆志「苟以天道時刻預定乾道十二年」，那個「乾道」
    是易義的天道，不是孝宗的年號；宋孝宗乾道只有九年）。

    短年號是長年號的後綴時要排除：「大通五年」在本語料裡三處全是
    「中大通五年」的一部分，照收會把梁武帝大通算成五年，於是鏈式
    核對誤報「中大通」的元年。
    """
    import collections
    per_book, per_year = collections.Counter(), collections.Counter()
    pat = re.compile(re.escape(era) + f"({NUM_RE})年")
    longer = _longer_eras(era)
    for b, t in text.items():
        for m in pat.finditer(t):
            i = m.start()
            if any(t[max(0, i - (len(L) - len(era))):i + len(era)] == L
                   for L in longer):
                continue                      # 其實是更長的那個年號
            n = cn_num(m.group(1))
            if n:
                per_book[b] += 1
                per_year[n] += 1
    if not per_year:
        return None, per_book
    # 只採出現兩次以上的年次。一次都沒有兩次的，就是判斷不了 ——
    # 回傳 None 而不是拿孤例充數。《宋史》引一紙文書的款識作
    # 「元興六年」，而東晉元興只有三年；靠那一處去推「義熙」的元年,
    # 報出來的是假警報。
    solid = [n for n, k in per_year.items() if k >= 2]
    return (max(solid) if solid else None), per_book


def check_eras(text, slack=30):
    """兩道核對，回傳 (斷代不符, 鏈式不符, 語料中查無, 相符數)。

    一、**斷代**：提到這個年號的書裡，有沒有一部的紀事年代容得下我給的
        元年。抓得到差一個世紀的錯（整朝記錯）。
    二、**鏈式**：年號在語料裡用到第幾年，應當接得上下一個年號的元年。
        「開元」用到二十九年 → 713＋29 ＝ 742 ＝「天寶」元年。
        抓得到差一年的錯 —— 第一道抓不到這種。

    同名年號（一名多朝）不入鏈式核對：它本來就有多個元年。
    """
    import collections
    dupe = {e for e, c in collections.Counter(x[0] for x in ERAS).items()
            if c > 1}
    span_bad, missing, ok = [], [], 0
    for era, y0, dyn in ERAS:
        _, books = era_usage(text, era)
        if not books:
            missing.append((era, y0, dyn))
        lo_hi = DYNASTY_SPAN.get(dyn)
        if lo_hi is None:
            continue
        if lo_hi[0] - slack <= y0 <= lo_hi[1] + slack:
            ok += 1
        else:
            span_bad.append((era, y0, dyn, lo_hi, books.most_common(3)))

    chain_bad = []
    by_dyn = collections.defaultdict(lambda: collections.defaultdict(set))
    for era, y0, dyn in ERAS:
        by_dyn[dyn][y0].add(era)
    for dyn, years in by_dyn.items():
        ys = sorted(years)
        for y0, y1 in zip(ys, ys[1:]):
            if any(n in dupe for n in years[y0] | years[y1]):
                continue
            got = [era_usage(text, n)[0] for n in years[y0]]
            got = [x for x in got if x]
            if not got:
                continue                  # 語料裡無從判斷，不報
            mx = max(got)
            implied = y0 + mx
            if abs(implied - y1) > 1:       # 改元多在年中，容許差一年
                chain_bad.append((dyn, "／".join(sorted(years[y0])), y0, mx,
                                  implied, "／".join(sorted(years[y1])), y1))
    return span_bad, chain_bad, missing, ok



def main():
    ap = argparse.ArgumentParser(description="對照 — 事件層並置")
    sub = ap.add_subparsers(dest="cmd", required=True)

    e = sub.add_parser("eras", help="紀年換算")
    e.add_argument("terms", nargs="+")
    e.add_argument("--book", help="來源書名，用於同名年號消歧，如 晋书")

    g = sub.add_parser("align", help="事件對照")
    g.add_argument("findings", help="huijian run 產出的 findings.json")
    g.add_argument("-t", "--threshold", type=int, default=4)
    g.add_argument("-o", "--out")

    k = sub.add_parser("checkeras", help="回語料核對年號表（需語料在位）")
    k.add_argument("--corpus", default="corpus")
    k.add_argument("--slack", type=int, default=30)

    a = ap.parse_args()
    if a.cmd == "eras":
        for t in a.terms:
            y = to_year(t, a.book)
            mon, leap, gz = parse_month_day(t)
            tail = ""
            if mon:
                tail += f"　{'閏' if leap else ''}{mon}月"
            if gz:
                tail += f"{gz}日"
            if y:
                print(f"{t:16s} → {y[0]} 年（{y[1]}{y[2]}）{tail}")
                continue
            cs = era_candidates(t)
            if not cs:
                print(f"{t:16s} → 未收，不猜")
            else:
                opts = "／".join(str(c[0]) for c in cs if c[1] == cs[0][1])
                print(f"{t:16s} → 同名年號「{cs[0][1]}」候選 {opts} —— 不猜"
                      f"（加 --book 書名消歧）")
        return

    if a.cmd == "checkeras":
        text = _corpus_text(a.corpus)
        print(f"語料 {len(text)} 部書，年號表 {len(ERAS)} 條", file=sys.stderr)
        span_bad, chain_bad, missing, ok = check_eras(text, a.slack)
        print(f"\n斷代核對（元年 vs 所標朝代）：相符 {ok}，"
              f"不符 {len(span_bad)}；語料中查無 {len(missing)}")
        for era, y0, dyn, lo_hi, bk in span_bad:
            print(f"  ⚠ {era}：我給元年 {y0}，而{dyn}的起訖是 "
                  f"{lo_hi[0]}–{lo_hi[1]}　語料分布 {bk}")
        print(f"\n鏈式核對：不符 {len(chain_bad)} 對")
        for dyn, era, y0, mx, imp, nxt, y1 in chain_bad:
            print(f"  ⚠ {dyn} {era}({y0}) 用到 {mx} 年 → 推得 {imp}，"
                  f"而下一個 {nxt} 作 {y1}　差 {imp-y1:+d}")
        if missing:
            print(f"\n語料中查無（{len(missing)} 條，多為本語料未用的簡繁"
                  f"異寫；留著以備他本，但**未經核對**）：")
            print("  " + "、".join(f"{e}({y})" for e, y, _ in missing[:40]))
        print("\n註：斷代核對抓得到整朝記錯；鏈式核對抓得到差一年。"
              "\n    兩道都過不等於全對 —— 語料未用到的年次核不出來。")
        return

    data = json.load(open(a.findings, encoding="utf-8"))
    rows = [h for p in data for h in p["hits"]] if data and "hits" in data[0] else data
    pairs = align(rows, a.threshold)
    show(pairs)
    if a.out:
        with open(a.out, "w", encoding="utf-8") as fh:
            show(pairs, fh)
        print(f"\n→ {a.out}", file=sys.stderr)


if __name__ == "__main__":
    main()
